// Batch guide cards: missing works part 1
import fs from "fs";
const R = fs.readFileSync("lib/bookpath-data.ts", "utf-8");
const O = R.indexOf("{", R.indexOf("export const bookPathData = "));
let d = 0, E = O;
for (let i = O; i < R.length; i++) { if (R[i] === "{") d++; else if (R[i] === "}") { d--; if (d === 0) { E = i + 1; break; } } }
const D = JSON.parse(R.slice(O, E));

function addGuide(t, diff, beg, pos, classic, read, sf, nsf, reason, advice, prereq = "") {
  const w = D.works.find(x => x.titleDisplayCn === t || x.titleDisplayCn.replace(/[《》]/g, "") === t);
  if (!w) { console.log(`Work not found: ${t}`); return; }
  if (w.guideCardIds?.length) { return; }
  const gid = `guide-${w.id}`;
  D.guideCards.push({
    id: gid, workId: w.id, title: w.titleDisplayCn,
    roleInPath: diff <= 2 ? "ENTRY" : diff === 3 ? "CORE" : "ADVANCED",
    suitability: "",
    oneSentencePositioning: pos, whyClassic: classic, whyRead: read,
    suitableFor: sf, notSuitableFor: nsf,
    difficultyLevel: diff, difficultyReason: reason,
    readingPrerequisites: prereq, readingAdvice: advice,
    beginnerEntry: beg, aiGenerated: false, reviewStatus: "AI_DRAFT",
  });
  if (!w.guideCardIds) w.guideCardIds = [];
  w.guideCardIds.push(gid);
  console.log(`+ ${t}`);
}

