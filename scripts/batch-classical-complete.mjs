function w(t, o, a, c, y, cat, sub, diff, beg, movs) {
  const slug = t.replace(/[^a-z0-9\u4e00-\u9fff]+/g, "-").replace(/^-+|-+$/g, "").toLowerCase();
  if (D.works.some(x => x.slug === slug)) { console.log(`Skip ${t}`); return null; }
  D.works.push({ id: slug, slug, titleDisplayCn: t, titleOriginal: o, authorName: a, countryOrRegion: c, firstPublishedYear: y, literaryCategory: cat, literarySubcategory: sub, workType: "长篇小说", difficultyLevel: diff, beginnerEntry: beg, movementIds: movs, guideCardIds: [] });
  return D.works[D.works.length - 1];
}

function g(work, rp, suit, pos, classic, read, sf, nsf, diff, reason, pre, adv, beg) {
  if (!work) return;
  const gid = `guide-${work.id}`;
  D.guideCards.push({ id: gid, workId: work.id, title: work.titleDisplayCn, roleInPath: rp, suitability: suit, oneSentencePositioning: pos, whyClassic: classic, whyRead: read, suitableFor: sf, notSuitableFor: nsf, difficultyLevel: diff, difficultyReason: reason, readingPrerequisites: pre, readingAdvice: adv, beginnerEntry: beg, aiGenerated: false, reviewStatus: "AI_DRAFT" });
  work.guideCardIds = [gid];
  console.log(`+ ${work.titleDisplayCn}`);
}

