import fs from "fs";
const R = fs.readFileSync("lib/bookpath-data.ts", "utf-8");
const O = R.indexOf("{", R.indexOf("export const bookPathData = "));
let d = 0, E = O;
for (let i = O; i < R.length; i++) { if (R[i] === "{") d++; else if (R[i] === "}") { d--; if (d === 0) { E = i + 1; break; } } }
const D = JSON.parse(R.slice(O, E));

function find(titleOrSlug) {
  const w = D.works.find(x =>
    x.slug === titleOrSlug ||
    x.titleDisplayCn === titleOrSlug ||
    x.titleDisplayCn.replace(/[《》]/g,"") === titleOrSlug ||
    x.titleOriginal === titleOrSlug
  );
  if (!w) console.log("  ⚠️ NOT FOUND:", titleOrSlug);
  return w;
}
function makeG(work, role, diff, beg, pos, classic, read, suit) {
  const gid = "guide-classic-" + work.id;
  return {
    id: gid, workId: work.id, title: work.titleDisplayCn,
    roleInPath: role, suitability: suit,
    oneSentencePositioning: pos, whyClassic: classic, whyRead: read,
    suitableFor: suit, notSuitableFor: "", difficultyLevel: diff,
    difficultyReason: suit, readingAdvice: pos,
    beginnerEntry: beg, aiGenerated: false, reviewStatus: "AI_DRAFT"
  };
}
function add(mid, guides) {
  const validGuides = guides.filter(g => g !== null);
  const m = D.movements.find(x => x.id === mid);
  if (!m) return console.log("NOT FOUND:", mid);
  m.guideCards = validGuides;
  console.log("✅", mid, validGuides.length, "guide cards");
}
function G(title, role, diff, beg, pos, classic, read, suit) {
  const w = find(title);
  return w ? makeG(w, role, diff, beg, pos, classic, read, suit) : null;
}

