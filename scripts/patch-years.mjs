let patchCount = 0;
for (const work of data.works) {
  if (work.firstPublishedYear != null) continue;
  // Strip 《》 for matching
  const key = work.titleDisplayCn.replace(/[《》]/g, "");
  const year = knownYears[key];
  if (year) {
    work.firstPublishedYear = year;
    patchCount++;
  }
}

