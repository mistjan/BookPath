// Add guide cards for newly added classical works
import fs from "fs";
const R = fs.readFileSync("lib/bookpath-data.ts", "utf-8");
const O = R.indexOf("{", R.indexOf("export const bookPathData = "));
let d = 0, E = O;
for (let i = O; i < R.length; i++) { if (R[i] === "{") d++; else if (R[i] === "}") { d--; if (d === 0) { E = i + 1; break; } } }
const D = JSON.parse(R.slice(O, E));

function addGuide(t, role, suit, pos, classic, read, suit4, notSuit, diff, reason, prereq, advice, beginner) {
  const w = D.works.find(x => x.titleDisplayCn === t);
  if (!w) { console.log(`Work not found: ${t}`); return; }
  if (w.guideCardIds && w.guideCardIds.length > 0) { console.log(`Skip ${t}: guide exists`); return; }
  const gid = `guide-${w.id}`;
  D.guideCards.push({
    id: gid, workId: w.id, title: t,
    roleInPath: role, suitability: suit,
    oneSentencePositioning: pos,
    whyClassic: classic, whyRead: read,
    suitableFor: suit4, notSuitableFor: notSuit,
    difficultyLevel: diff, difficultyReason: reason,
    readingPrerequisites: prereq, readingAdvice: advice,
    beginnerEntry: beginner, aiGenerated: false, reviewStatus: "AI_DRAFT",
  });
  if (!w.guideCardIds) w.guideCardIds = [];
  w.guideCardIds.push(gid);
  console.log(`+ Guide: ${t}`);
}

